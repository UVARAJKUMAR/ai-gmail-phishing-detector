# ============================================================
# GMAIL CONNECTION
# ============================================================

def connect_gmail():
    """
    Connect to Gmail using IMAP.
    """

    mail = imaplib.IMAP4_SSL(
        IMAP_HOST,
        IMAP_PORT
    )

    mail.login(
        GMAIL_ADDRESS,
        GMAIL_APP_PASSWORD
    )

    mail.select("INBOX")

    return mail


# ============================================================
# CHECK WHETHER EMAIL IS OUR OWN SECURITY ALERT
# ============================================================

def is_own_security_alert(msg):
    """
    Return True when the message is generated by this detector.

    The dedicated X-Phishing-Detector-Alert header is the primary
    identifier. The sender/subject check is kept as a backward-compatible
    fallback for older alert emails.
    """

    detector_header = str(
        msg.get("X-Phishing-Detector-Alert", "")
    ).strip().lower()

    if detector_header == "true":
        return True

    subject = str(msg.get("Subject", ""))
    sender = str(msg.get("From", ""))

    subject_upper = subject.upper()
    sender_lower = sender.lower()
    gmail_lower = GMAIL_ADDRESS.lower()

    own_sender = gmail_lower in sender_lower
    own_subject = (
        "[SECURITY ALERT]" in subject_upper
        or "[PHISHING ALERT]" in subject_upper
    )

    return own_sender and own_subject


# ============================================================
# SEND EXACTLY ONE ALERT
# ============================================================

def send_one_alert(uid, result):
    """
    Send at most one alert for an already-recorded phishing email.

    The caller must save the analysis result before this function is called.
    That guarantees a failed SMTP attempt does not cause the email to be
    analyzed again on the next polling cycle.
    """

    if alert_already_sent(uid):
        logging.info(
            "UID=%s already has an alert. NO SECOND ALERT WILL BE SENT.",
            uid
        )
        return False

    try:
        logging.info("Sending security alert for UID=%s", uid)
        send_alert(result)
        mark_alert_sent(uid)

        logging.info(
            "SUCCESS: exactly ONE alert sent for UID=%s",
            uid
        )
        return True

    except Exception:
        logging.exception(
            "Alert failed for UID=%s. The email is already marked as scanned; "
            "it will NOT be analyzed again.",
            uid
        )
        return False


# ============================================================
# PROCESS ONE EMAIL
# ============================================================

def process_email(mail, uid_bytes):

    uid = uid_bytes.decode(
        errors="ignore"
    )


    # ========================================================
    # CHECK WHETHER ALREADY SCANNED
    # ========================================================

    if already_scanned(uid):

        logging.info(
            "UID=%s already scanned. Skipping.",
            uid
        )

        return


    # ========================================================
    # FETCH EMAIL
    # ========================================================

    status, message_data = mail.uid(
        "fetch",
        uid,
        "(RFC822)"
    )


    if status != "OK":

        logging.warning(
            "Could not fetch UID=%s",
            uid
        )

        return


    # ========================================================
    # EXTRACT RAW EMAIL
    # ========================================================

    raw = next(
        (
            item[1]
            for item in message_data
            if (
                isinstance(item, tuple)
                and len(item) > 1
                and isinstance(item[1], bytes)
            )
        ),
        None
    )


    if not raw:

        logging.warning(
            "No email content for UID=%s",
            uid
        )

        return


    # ========================================================
    # PARSE EMAIL
    # ========================================================

    msg = parse_email(raw)


    subject = str(
        msg.get("Subject", "")
    )

    sender = str(
        msg.get("From", "")
    )


    logging.info(
        "Processing UID=%s | From=%s | Subject=%s",
        uid,
        sender,
        subject
    )


    # ========================================================
    # IGNORE OUR OWN ALERT
    # ========================================================

    if is_own_security_alert(msg):

        logging.info(
            "Detector-generated alert found. "
            "Ignoring UID=%s",
            uid
        )


        save_result(
            uid,
            msg.get("Message-ID", ""),
            sender,
            subject,
            "IGNORED",
            0,
            [
                "Detector-generated security alert"
            ]
        )

        return


    # ========================================================
    # EXTRACT EMAIL BODY / URLS / ATTACHMENTS
    # ========================================================

    body, urls = get_body_and_urls(msg)

    attachments = get_attachments(msg)


    # ========================================================
    # ANALYZE EMAIL
    # ========================================================

    result = analyze_email(
        msg,
        body,
        urls,
        attachments
    )


    risk = result.get(
        "risk_level",
        "LOW"
    )

    score = result.get(
        "score",
        0
    )

    reasons = result.get(
        "reasons",
        []
    )


    logging.info(
        "UID=%s | Risk=%s | Score=%s",
        uid,
        risk,
        score
    )


    # ========================================================
    # DETERMINE ALERT CONDITION
    # ========================================================

    should_alert = (
        risk in {
            "HIGH",
            "CRITICAL"
        }
        or
        (
            risk == "MEDIUM"
            and ALERT_ON_MEDIUM
        )
    )


    # ========================================================
    # SAVE ANALYSIS RESULT FIRST
    # ========================================================
    # This is important: once analysis is complete, the UID is
    # permanently recorded. If SMTP later fails, the original email
    # will not be analyzed again on the next polling cycle.

    save_result(
        uid,
        msg.get("Message-ID", ""),
        result.get("sender", sender),
        result.get("subject", subject),
        risk,
        score,
        reasons
    )

    # ========================================================
    # NORMAL EMAIL
    # ========================================================

    if not should_alert:
        logging.info(
            "UID=%s is normal. No alert generated.",
            uid
        )
        return

    # ========================================================
    # PHISHING / HIGH RISK EMAIL
    # ========================================================

    logging.warning(
        "PHISHING/HIGH-RISK EMAIL DETECTED | UID=%s",
        uid
    )

    # ========================================================
    # ONE ALERT PER PHISHING EMAIL
    # ========================================================

    alert_sent = send_one_alert(uid, result)

    if alert_sent:
        logging.info(
            "UID=%s completely processed. Analysis saved and one alert sent.",
            uid
        )
    else:
        logging.warning(
            "UID=%s analysis saved, but alert was not sent successfully. "
            "The email will not be analyzed again.",
            uid
        )


# ============================================================
# PROCESS ONE GMAIL CYCLE
# ============================================================

def process_cycle():

    mail = None

    try:

        # ----------------------------------------------------
        # CONNECT
        # ----------------------------------------------------

        mail = connect_gmail()


        # ----------------------------------------------------
        # SEARCH ONLY UNSEEN EMAILS
        # ----------------------------------------------------

        status, data = mail.uid(
            "search",
            None,
            "UNSEEN"
        )


        if status != "OK":

            logging.error(
                "Could not search Gmail inbox."
            )

            return


        all_uids = data[0].split()


        if not all_uids:

            logging.info(
                "No new emails."
            )

            return


        # ----------------------------------------------------
        # LIMIT EMAILS PER CYCLE
        # ----------------------------------------------------

        uids = all_uids[
            -MAX_EMAILS_PER_CYCLE:
        ]


        logging.info(
            "Found %d new email(s).",
            len(uids)
        )


        # ----------------------------------------------------
        # PROCESS EACH EMAIL
        # ----------------------------------------------------

        for uid_bytes in uids:

            try:

                process_email(
                    mail,
                    uid_bytes
                )

            except Exception:

                logging.exception(
                    "Error processing one email."
                )

                continue


    except imaplib.IMAP4.error:

        logging.exception(
            "Gmail IMAP error."
        )


    except Exception:

        logging.exception(
            "Unexpected processing error."
        )


    finally:

        # ----------------------------------------------------
        # CLOSE CONNECTION
        # ----------------------------------------------------

        if mail is not None:

            try:

                mail.close()

            except Exception:

                pass


            try:

                mail.logout()

            except Exception:

                pass


