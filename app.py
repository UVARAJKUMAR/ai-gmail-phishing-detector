        try:

            process_cycle()

        except Exception:

            logging.exception(
                "Fatal cycle error."
            )


        # ----------------------------------------------------
        # WAIT BEFORE NEXT CHECK
        # ----------------------------------------------------

        time.sleep(
            POLL_SECONDS
        )


